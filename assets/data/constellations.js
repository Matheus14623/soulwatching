function freezeConstellation(constellation) {
  return Object.freeze({
    ...constellation,
    sourceIds: Object.freeze([...constellation.sourceIds]),
    relatedConstellationIds: Object.freeze([...constellation.relatedConstellationIds]),
    stars: Object.freeze(constellation.stars.map((star) => Object.freeze({ ...star }))),
    lines: Object.freeze(constellation.lines.map((line) => Object.freeze([...line]))),
  });
}


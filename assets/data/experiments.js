function freezeExperiment(experiment) {
  return Object.freeze({
    ...experiment,
    theoryIds: Object.freeze([...experiment.theoryIds]),
  });
}

export const EXPERIMENTS = Object.freeze(rawExperiments.map(freezeExperiment));

export function findExperiment(id, fallback = null) {
  return EXPERIMENTS.find((experiment) => experiment.id === id || experiment.slug === id) || fallback;
}

export function getExperimentKind(id) {
  return EXPERIMENT_KINDS.find((kind) => kind.id === id) || null;
}

export function getActiveExperiments() {
  return EXPERIMENTS.filter((experiment) => experiment.status === 'active');
}
